#!/usr/bin/env bash
# Rebuild the benchmark workload (needs an m68k cross GCC, e.g. Ubuntu's
# gcc-m68k-linux-gnu) and regenerate bench_rom.h, which is committed so the host
# and firmware benchmark builds need no 68k toolchain.
set -euo pipefail
cd "$(dirname "$0")"
CC=${M68K_CC:-m68k-linux-gnu-gcc}
OBJCOPY=${M68K_OBJCOPY:-m68k-linux-gnu-objcopy}
$CC -mcpu=68000 -O2 -ffreestanding -fno-builtin -fno-pic -nostdlib -fno-stack-protector \
    -Wall -Wextra -Wa,--noexecstack -T link.ld -Wl,--build-id=none -o bench.elf crt0.S bench.c
if m68k-linux-gnu-nm -u bench.elf | grep -q .; then
    echo "unresolved symbols (libgcc helpers are not available on a 68000 target):" >&2
    m68k-linux-gnu-nm -u bench.elf >&2; exit 1
fi
$OBJCOPY -O binary bench.elf bench.bin
python3 - <<'PY'
data = open("bench.bin", "rb").read()
with open("../bench_rom.h", "w") as f:
    f.write("/* Generated by src/bench/workload/build.sh from bench.c; do not edit. */\n")
    f.write("#pragma once\n#include <stdint.h>\n")
    f.write("static const uint8_t bench_rom[%d] = {\n" % len(data))
    for i in range(0, len(data), 16):
        f.write("    " + ", ".join("0x%02X" % b for b in data[i:i+16]) + ",\n")
    f.write("};\n")
PY
rm -f bench.elf bench.bin
echo "bench_rom.h: $(grep -c 0x ../bench_rom.h) lines"
