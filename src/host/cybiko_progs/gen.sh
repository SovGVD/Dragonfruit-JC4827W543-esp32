#!/bin/sh
# Regenerates ../cybiko_progs.h from the .s files here. Needs the GNU H8
# binutils (Debian/Ubuntu: binutils-h8300-hms).
set -e
cd "$(dirname "$0")"
out=../cybiko_progs.h
tmp=$(mktemp -d)
echo "/* Generated by cybiko_progs/gen.sh from the .s files there; do not edit. */" > $out
echo "#pragma once" >> $out
for s in *.s; do
    n=$(basename $s .s)
    h8300-hitachi-coff-as $s -o $tmp/$n.o
    h8300-hitachi-coff-ld -mh8300s -Ttext=0 -o $tmp/$n.x $tmp/$n.o 2>/dev/null
    h8300-hitachi-coff-objcopy -O binary $tmp/$n.x $tmp/$n.bin
    echo "static const unsigned char prog_$n[] = {" >> $out
    od -An -v -tx1 $tmp/$n.bin | sed 's/ *\([0-9a-f][0-9a-f]\)/0x\1,/g; s/^/   /' >> $out
    echo "};" >> $out
done
rm -rf $tmp
